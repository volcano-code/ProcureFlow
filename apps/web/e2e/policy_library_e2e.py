"""Actual native browser/HTTP library flow. Run via verify_next.py."""
from workbench_e2e import page, URL
from playwright.sync_api import expect


def test_native_reference_library_publish_search_and_withdraw(page):
    page.goto(URL)
    page.get_by_test_id('login-demo-buyer').click()
    page.get_by_label('切换演示身份').select_option('demo-approver')
    expect(page.get_by_test_id('identity')).to_have_text('approver')
    library=page.get_by_test_id('policy-library')
    library.locator('summary').first.click()
    library.get_by_text('发布新的参考版本／撤回',exact=True).click()
    form=library.get_by_test_id('library-publish-form')
    form.locator('[name=key]').fill('browser-reference')
    form.locator('[name=title]').fill('浏览器运费核查制度')
    form.locator('[name=source]').fill('synthetic-browser')
    form.locator('[name=content]').fill('运费必须明确，未知费用不得归零。')
    form.locator('[name=reason]').fill('原生浏览器发布测试')
    form.get_by_role('button',name='发布参考版本',exact=True).click()
    expect(library.get_by_role('status')).to_contain_text('v1 已发布')
    library.get_by_label('制度检索问题').fill('运费')
    library.get_by_role('button',name='检索参考文档',exact=True).click()
    expect(library.get_by_test_id('library-results')).to_contain_text('未知费用不得归零')
    library.get_by_role('button',name='回读此版本原文').click()
    expect(library.get_by_test_id('library-original')).to_contain_text('运费必须明确')
    form.locator('[name=key]').fill('browser-reference')
    form.locator('[name=version]').fill('1')
    form.locator('[name=title]').fill('浏览器运费核查制度')
    form.locator('[name=source]').fill('synthetic-browser')
    form.locator('[name=reason]').fill('原生浏览器撤回测试')
    form.locator('[name=withdrawn]').check()
    form.get_by_role('button',name='发布参考版本',exact=True).click()
    expect(library.get_by_role('status')).to_contain_text('v2 已发布')
    library.get_by_role('button',name='检索参考文档',exact=True).click()
    expect(library.get_by_test_id('library-results')).to_contain_text('未找到匹配资料')
    library.get_by_role('button',name='回读文档历史').click()
    expect(library).to_contain_text('已撤回')
    page.get_by_label('切换演示身份').select_option('demo-buyer')
    expect(page.get_by_test_id('identity')).to_have_text('buyer')
    expect(page.get_by_test_id('library-publish-form')).to_have_count(0)
