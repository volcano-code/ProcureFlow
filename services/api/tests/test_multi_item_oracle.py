"""Frozen deterministic multi-item oracle tests.

Expected values are hand-authored in evals/procurement/multi-item-oracle-v1.json;
they are not generated by the production calculator or a shared helper.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest
from procureflow.contracts import QuoteValues
from procureflow.domain import calculate


ROOT = Path(__file__).resolve().parents[3]
ORACLE = ROOT / "evals" / "procurement" / "multi-item-oracle-v1.json"


def load_oracle():
    suite = json.loads(ORACLE.read_text(encoding="utf-8"))
    assert suite["schema_version"] == 1
    assert suite["suite_id"] == "procureflow-multi-item-deterministic-oracle-v1"
    assert len(suite["cases"]) == 6
    assert len({case["id"] for case in suite["cases"]}) == len(suite["cases"])
    return suite


@pytest.mark.parametrize("case", load_oracle()["cases"], ids=lambda case: case["id"])
def test_multi_item_calculator_matches_frozen_independent_oracle(case):
    result = calculate(QuoteValues.model_validate(case["quote"]))
    expected = case["expected"]

    for field in ("comparable", "total", "goods", "discount", "added_tax", "shipping", "missing", "errors"):
        assert result[field] == expected[field], f"{case['id']}: {field}"

    assert len(result["lines"]) == len(expected["line_totals"])
    for index, line in enumerate(result["lines"]):
        assert line.get("total") == expected["line_totals"][index], f"{case['id']}: line {index} total"
        assert line.get("goods") == expected["line_goods"][index], f"{case['id']}: line {index} goods"
        assert line.get("discount") == expected["line_discounts"][index], f"{case['id']}: line {index} discount"
        assert line.get("added_tax") == expected["line_added_tax"][index], f"{case['id']}: line {index} added tax"


def test_multi_item_oracle_has_no_runtime_generated_expected_values():
    suite = load_oracle()
    assert all("expected" in case for case in suite["cases"])
    assert all(case["expected"]["total"] is None or isinstance(case["expected"]["total"], str)
               for case in suite["cases"])
    assert all(case["expected"]["line_totals"] for case in suite["cases"])
